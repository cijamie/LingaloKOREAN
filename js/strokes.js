// LingaloKR stroke order for writing practice.
// Each letter is a list of strokes in writing order; each stroke is a list of [x, y] points
// on a 100 × 100 grid, drawn from the first point to the last.
// Korean strokes go top to bottom and left to right.

const STROKES = (() => {
    const circle = (cx, cy, r) => Array.from({ length: 25 }, (_, i) => {
        // Start at the top and go counterclockwise, the way ㅇ is written.
        const a = -Math.PI / 2 - (i / 24) * Math.PI * 2;
        return [Math.round(cx + r * Math.cos(a)), Math.round(cy + r * Math.sin(a))];
    });

    const base = {
        /* Consonants */
        'ㄱ': [[[20, 22], [76, 22], [76, 86]]],
        'ㄴ': [[[24, 14], [24, 80], [84, 80]]],
        'ㄷ': [[[24, 20], [78, 20]], [[24, 20], [24, 80], [82, 80]]],
        'ㄹ': [[[22, 14], [76, 14], [76, 48]], [[22, 48], [76, 48]], [[22, 48], [22, 86], [82, 86]]],
        'ㅁ': [[[22, 18], [22, 82]], [[22, 18], [78, 18], [78, 82]], [[22, 82], [78, 82]]],
        'ㅂ': [[[25, 14], [25, 86]], [[75, 14], [75, 86]], [[25, 50], [75, 50]], [[25, 86], [75, 86]]],
        'ㅅ': [[[52, 14], [18, 86]], [[38, 44], [84, 86]]],
        'ㅇ': [circle(50, 50, 32)],
        'ㅈ': [[[20, 20], [80, 20]], [[50, 20], [18, 86]], [[38, 46], [84, 86]]],
        'ㅊ': [[[50, 4], [50, 16]], [[20, 26], [80, 26]], [[50, 26], [18, 88]], [[38, 51], [84, 88]]],
        'ㅋ': [[[20, 20], [76, 20], [76, 86]], [[20, 52], [76, 52]]],
        'ㅌ': [[[25, 16], [78, 16]], [[25, 48], [76, 48]], [[25, 16], [25, 82], [82, 82]]],
        'ㅍ': [[[18, 20], [82, 20]], [[36, 20], [36, 80]], [[64, 20], [64, 80]], [[14, 80], [86, 80]]],
        'ㅎ': [[[50, 6], [50, 18]], [[22, 26], [78, 26]], circle(50, 63, 22)],

        /* Basic vowels: the long line and the short strokes */
        'ㅏ': [[[42, 8], [42, 92]], [[42, 50], [74, 50]]],
        'ㅑ': [[[42, 8], [42, 92]], [[42, 38], [74, 38]], [[42, 62], [74, 62]]],
        'ㅓ': [[[28, 50], [60, 50]], [[60, 8], [60, 92]]],
        'ㅕ': [[[28, 38], [60, 38]], [[28, 62], [60, 62]], [[60, 8], [60, 92]]],
        'ㅗ': [[[50, 32], [50, 62]], [[10, 62], [90, 62]]],
        'ㅛ': [[[38, 32], [38, 62]], [[62, 32], [62, 62]], [[10, 62], [90, 62]]],
        'ㅜ': [[[10, 40], [90, 40]], [[50, 40], [50, 74]]],
        'ㅠ': [[[10, 40], [90, 40]], [[38, 40], [38, 74]], [[62, 40], [62, 74]]],
        'ㅡ': [[[10, 50], [90, 50]]],
        'ㅣ': [[[50, 8], [50, 92]]]
    };

    // Squeeze a letter into the horizontal band x0–x1.
    const fit = (strokes, x0, x1) => strokes.map(s => s.map(([x, y]) => [Math.round(x0 + (x / 100) * (x1 - x0)), y]));
    const side = (a, b, split = 50) => [...fit(base[a], 0, split), ...fit(base[b], split, 100)];

    return {
        ...base,
        /* Double consonants: the same letter twice, left one first */
        'ㄲ': side('ㄱ', 'ㄱ'), 'ㄸ': side('ㄷ', 'ㄷ'), 'ㅃ': side('ㅂ', 'ㅂ'), 'ㅆ': side('ㅅ', 'ㅅ'), 'ㅉ': side('ㅈ', 'ㅈ'),
        /* Combined vowels: written left part first, then the right */
        'ㅐ': side('ㅏ', 'ㅣ', 62), 'ㅔ': side('ㅓ', 'ㅣ', 62), 'ㅒ': side('ㅑ', 'ㅣ', 62), 'ㅖ': side('ㅕ', 'ㅣ', 62),
        'ㅘ': side('ㅗ', 'ㅏ', 55), 'ㅙ': [...fit(base['ㅗ'], 0, 50), ...fit(side('ㅏ', 'ㅣ', 62), 50, 100)], 'ㅚ': side('ㅗ', 'ㅣ', 62),
        'ㅝ': side('ㅜ', 'ㅓ', 55), 'ㅞ': [...fit(base['ㅜ'], 0, 50), ...fit(side('ㅓ', 'ㅣ', 62), 50, 100)], 'ㅟ': side('ㅜ', 'ㅣ', 62),
        'ㅢ': side('ㅡ', 'ㅣ', 62)
    };
})();
